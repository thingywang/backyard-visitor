"""Prepare and run a detached, logged PyInstaller macOS app build.

--check makes no changes. --install-builder opts into installing PyInstaller in
the current Python environment, inside the detached worker. Build only on macOS.
"""
from __future__ import annotations

import argparse
import ast
from datetime import datetime, timezone
import importlib.util
import json
import os
from pathlib import Path
import platform
import shlex
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
BUILD = ROOT / "build" / "macos"
DIST = ROOT / "dist"
APP_NAME = "BackyardVisitor"
BUILDER_REQUIREMENT = "PyInstaller>=6.22,<7"


def write_json(path: Path, value: dict) -> None:
    temporary = path.with_name(f"{path.name}.{os.getpid()}.tmp")
    temporary.write_text(json.dumps(value, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    temporary.replace(path)


def verify_sources() -> list[str]:
    failures = []
    if sys.platform != "darwin":
        failures.append("macOS .app 必须在 macOS 上打包。")
    if sys.version_info < (3, 10):
        failures.append("需要 Python 3.10 或更新版本。")
    for relative in ("backyard_visitor/app.py", "scripts/entry.py", "scripts/compile_sprite_cache.py"):
        path = ROOT / relative
        if not path.is_file():
            failures.append(f"缺少 {relative}，请先完成应用源码。")
            continue
        try:
            ast.parse(path.read_text(encoding="utf-8"), filename=relative)
        except (OSError, SyntaxError) as exc:
            failures.append(f"{relative} 无法解析：{exc}")
    try:
        from PyQt6.QtCore import PYQT_VERSION_STR
        if PYQT_VERSION_STR != "6.9.1":
            failures.append("请使用已安装 PyQt6 6.9.1 的项目 .venv。")
    except ImportError:
        failures.append("缺少 PyQt6，请先运行 launch.command 安装运行依赖。")
    assets = ROOT / "backyard_visitor" / "assets"
    for name in ("cats.png", "sprites.json", "extra.png", "extra.json",
                 "interactions.png", "interactions.json", "gifts.png", "gifts.json",
                 "standing.png", "standing.json", "settling.png", "settling.json", "jump_transitions.png", "jump_transitions.json", "run.png", "run.json", "bowl.png", "bowl.json", "activity.png", "activity.json", "rear-tail-source.png", "rear-tail.json", "posture.png", "posture-belly.png", "posture.json", "locomotion.json", "locomotion-front-contact.png", "locomotion-hind-passing.png",
                 "locomotion-back-contact.png", "locomotion-front-passing.png",
                 "backyard-dusk.png", "backyard-dusk.json", "backyard-morning.png", "backyard-morning.json",
                 "backyard-cat-tree-portrait.png", "backyard-cat-tree-portrait.json", "resident-bed.png"):
        if not (assets / name).is_file():
            failures.append(f"缺少素材 {name}。")
    return failures


def spec_text() -> str:
    # This is the spec equivalent of --windowed --onedir. BUNDLE info_plist
    # entries are supplied before PyInstaller's normal local ad-hoc signing.
    return f'''# Generated by scripts/build_macos.py; do not edit by hand.
a = Analysis(
    [{str(ROOT / "scripts" / "entry.py")!r}],
    pathex=[{str(ROOT)!r}],
    binaries=[],
    datas=[({str(ROOT / "backyard_visitor" / "assets")!r}, "backyard_visitor/assets")],
    hiddenimports=[],
    hookspath=[],
    runtime_hooks=[],
    excludes=["PySide6", "PySide2", "PyQt5"],
    noarchive=False,
)
pyz = PYZ(a.pure)
exe = EXE(
    pyz, a.scripts, [], exclude_binaries=True,
    name={APP_NAME!r}, debug=False, bootloader_ignore_signals=False,
    strip=False, upx=False, console=False, argv_emulation=False,
    target_arch=None, codesign_identity=None, entitlements_file=None,
)
coll = COLLECT(exe, a.binaries, a.datas, strip=False, upx=False, name={APP_NAME!r})
app = BUNDLE(
    coll, name={APP_NAME + ".app"!r}, icon={str(ROOT / "backyard_visitor" / "assets" / "backyard-icon.icns")!r},
    bundle_identifier="local.backyardvisitor.desktop",
    version="0.9.4",
    info_plist={{
        "CFBundleDisplayName": "后院访客",
        "LSUIElement": True,
        "LSMinimumSystemVersion": "12.0",
        "NSPrincipalClass": "NSApplication",
        "NSHighResolutionCapable": True,
        "NSAppleEventsUsageDescription": "仅在您启用图标互动后读取 Finder 桌面图标的位置和名称，不移动或删除文件。",
    }},
)
'''


def run_worker(install_builder: bool) -> int:
    status_path = BUILD / "status.json"
    started = datetime.now(timezone.utc).isoformat()
    common = {"started_at": started, "pid": os.getpid(), "architecture": platform.machine()}
    write_json(status_path, {**common, "state": "building"})
    try:
        if importlib.util.find_spec("PyInstaller") is None:
            if not install_builder:
                raise RuntimeError("PyInstaller 未安装。请添加 --install-builder 后重新运行。")
            print("正在安装可选打包工具；运行版不需要此工具。", flush=True)
            subprocess.run(
                [sys.executable, "-m", "pip", "install", "--disable-pip-version-check", BUILDER_REQUIREMENT],
                check=True,
            )
        # Cache generation is mandatory and uses the same project interpreter.
        # Offscreen is local to this child; packaging keeps the caller's Qt env.
        cache_command = [sys.executable, str(ROOT / "scripts" / "compile_sprite_cache.py"), "--force-source"]
        cache_environment = os.environ.copy()
        cache_environment["QT_QPA_PLATFORM"] = "offscreen"
        print(shlex.join(cache_command), flush=True)
        subprocess.run(cache_command, cwd=ROOT, env=cache_environment, check=True)
        subprocess.run([sys.executable, str(ROOT / "scripts" / "compile_rear_tail.py")],
                       cwd=ROOT, env=cache_environment, check=True)
        spec = BUILD / "BackyardVisitor.spec"
        spec.write_text(spec_text(), encoding="utf-8")
        command = [
            sys.executable, "-m", "PyInstaller", "--noconfirm", "--clean",
            "--distpath", str(DIST), "--workpath", str(BUILD / "work"), str(spec),
        ]
        print(shlex.join(command), flush=True)
        environment = os.environ.copy()
        environment["PYINSTALLER_CONFIG_DIR"] = str(BUILD / "cache")
        subprocess.run(command, cwd=ROOT, env=environment, check=True)
        bundle = DIST / f"{APP_NAME}.app"
        if not (bundle / "Contents" / "MacOS" / APP_NAME).is_file():
            raise RuntimeError("打包进程已结束，但未找到预期的 .app 主程序。")
        write_json(status_path, {**common, "state": "complete", "app": str(bundle),
                                "finished_at": datetime.now(timezone.utc).isoformat()})
        print(f"完成：{bundle}\n这是本机测试包；未配置发布签名或公证。", flush=True)
        return 0
    except Exception as exc:
        write_json(status_path, {**common, "state": "failed", "error": str(exc),
                                "finished_at": datetime.now(timezone.utc).isoformat()})
        print(f"打包失败：{exc}", file=sys.stderr, flush=True)
        return 1


def main() -> int:
    parser = argparse.ArgumentParser(description="生成后院访客 macOS .app")
    parser.add_argument("--check", action="store_true", help="只检查源码和依赖，不打包")
    parser.add_argument("--install-builder", action="store_true", help="在后台安装缺少的 PyInstaller")
    parser.add_argument("--worker", action="store_true", help=argparse.SUPPRESS)
    args = parser.parse_args()
    failures = verify_sources()
    if failures:
        print("\n".join(failures), file=sys.stderr)
        return 1
    has_builder = importlib.util.find_spec("PyInstaller") is not None
    if args.check:
        print(f"源码、素材、Qt 检查通过；目标架构 {platform.machine()}。")
        print("PyInstaller 已安装。" if has_builder else "PyInstaller 尚未安装；首次打包可加 --install-builder。")
        return 0
    if args.worker:
        return run_worker(args.install_builder)
    if not has_builder and not args.install_builder:
        print("缺少可选打包工具。请运行：\n.venv/bin/python scripts/build_macos.py --install-builder", file=sys.stderr)
        return 1
    BUILD.mkdir(parents=True, exist_ok=True)
    # One build at a time avoids replacing an in-progress bundle.
    job_path = BUILD / "job.json"
    if job_path.exists():
        try:
            previous = json.loads(job_path.read_text(encoding="utf-8"))
            os.kill(int(previous["pid"]), 0)
        except (OSError, ValueError, KeyError, TypeError):
            pass
        else:
            status_path = BUILD / "status.json"
            state = json.loads(status_path.read_text(encoding="utf-8")) if status_path.exists() else {}
            if state.get("state") not in {"complete", "failed"}:
                print(f"已有后台打包进程。日志：{BUILD / 'build.log'}")
                return 0
    log_path = BUILD / "build.log"
    command = [sys.executable, "-u", str(Path(__file__).resolve()), "--worker"]
    if args.install_builder:
        command.append("--install-builder")
    with log_path.open("w", encoding="utf-8") as log:
        child = subprocess.Popen(command, cwd=ROOT, stdin=subprocess.DEVNULL, stdout=log,
                                 stderr=subprocess.STDOUT, start_new_session=True)
    write_json(job_path, {"pid": child.pid, "log": str(log_path), "status": str(BUILD / "status.json"),
                          "submitted_at": datetime.now(timezone.utc).isoformat()})
    print(f"已在后台开始打包，进程号 {child.pid}。可以关闭终端。")
    print(f"日志：{log_path}\n状态：{BUILD / 'status.json'}\n成功后：{DIST / (APP_NAME + '.app')}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
